export function isGeneratedBotId(value: unknown): value is string {
  return typeof value === "string" && GENERATED_BOT_ID.test(value);
}

export function assertGeneratedBotId(value: unknown): asserts value is string {
  if (isGeneratedBotId(value)) return;
  throw Object.assign(
    new Error("Invalid Bot ID: expected the lowercase UUID v4 format generated by OpenBot"),
    { status: 400, code: "INVALID_BOT_ID" },
  );
}

