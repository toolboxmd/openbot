function writeIsolatedConfig(configPath: string, workspaceDir: string): void {
  const workspace = path.resolve(workspaceDir);
  if (!fs.existsSync(configPath)) {
    replaceFileAtomic(configPath, appendTrustedWorkspace(ISOLATED_CONFIG_BODY, workspace), 0o644);
    return;
  }
  const originalBody = fs.readFileSync(configPath, "utf8");
  let body = originalBody;
  body = updateTopLevelToml(body, scanTomlDocument(body), [
    ["sandbox_mode", '"danger-full-access"'],
    ["allow_login_shell", "false"],
  ]);
  const updatedDocument = scanTomlDocument(body);
  const workspaceTables = updatedDocument.tables.filter(
    (table) => table.key.length === 2 && table.key[0] === "projects" && table.key[1] === workspace,
  );
  if (workspaceTables.some((table) => table.array)) {
    throw new Error(
      "Cannot update Isolated config: workspace project entry must be a normal TOML table, not an array table",
    );
  }
  if (workspaceTables.length > 1) {
    throw new Error("Cannot update Isolated config: duplicate workspace project TOML table");
  }
  const rootProjectsValue = updatedDocument.rootAssignments.some(
    (assignment) => assignment.key.length === 1 && assignment.key[0] === "projects",
  );
  if (rootProjectsValue) {
    throw new Error(
      "Cannot update Isolated config: workspace project entry has an incompatible inline TOML shape",
    );
  }
  const dottedWorkspaceAssignments = [
    ...updatedDocument.rootAssignments
      .filter((assignment) => assignment.key[0] === "projects" && assignment.key[1] === workspace)
      .map((assignment) => ({ assignment, key: assignment.key })),
    ...updatedDocument.tables.flatMap((table) => {
      if (table.key.length !== 1 || table.key[0] !== "projects") return [];
      const matches = table.assignments
        .filter((assignment) => assignment.key[0] === workspace)
        .map((assignment) => ({ assignment, key: ["projects", ...assignment.key] }));
      if (matches.length > 0 && table.array) {
        throw new Error(
          "Cannot update Isolated config: workspace project entry must not belong to an array table",
        );
      }
      return matches;
    }),
  ];
  if (workspaceTables.length > 0 && dottedWorkspaceAssignments.length > 0) {
    throw new Error("Cannot update Isolated config: conflicting workspace project entries");
  }
  const dottedTrustAssignments = dottedWorkspaceAssignments.filter(
    ({ key }) => key.length === 3 && key[2] === "trust_level",
  );
  if (dottedWorkspaceAssignments.length > 0 && dottedTrustAssignments.length !== 1) {
    throw new Error(
      "Cannot update Isolated config: dotted workspace project must contain exactly one trust_level assignment",
    );
  }
  const workspaceTable = workspaceTables[0];
  if (workspaceTable) {
    body = updateTomlAssignments(
      body,
      workspaceTable.assignments,
      workspaceTable.end,
      [["trust_level", '"trusted"']],
      "workspace project",
    );
  } else if (dottedTrustAssignments.length === 1) {
    const { assignment } = dottedTrustAssignments[0];
    body = replaceTomlValue(body, assignment, '"trusted"');
  } else {
    body = appendTrustedWorkspace(body, workspace);
  }
  if (body === originalBody) return;
  const mode = fs.statSync(configPath).mode & 0o777;
  replaceFileAtomic(configPath, body, mode);
}

function appendTrustedWorkspace(text: string, workspace: string): string {
  const newline = text.includes("\r\n") ? "\r\n" : "\n";
  const separator = text.length === 0
    ? ""
    : text.endsWith(`${newline}${newline}`)
      ? ""
      : text.endsWith(newline)
        ? newline
        : `${newline}${newline}`;
  return `${text}${separator}[projects.${JSON.stringify(workspace)}]${newline}trust_level = "trusted"${newline}`;
}

type TomlAssignment = {
  key: string[];
  valueStart: number;
  valueEnd: number;
};

type TomlTable = {
  key: string[];
  array: boolean;
  end: number;
  assignments: TomlAssignment[];
};

type TomlDocument = {
  rootAssignments: TomlAssignment[];
  rootEnd: number;
  tables: TomlTable[];
};

function scanTomlDocument(text: string): TomlDocument {
  const rootAssignments: TomlAssignment[] = [];
  const tables: TomlTable[] = [];
  let rootEnd = text.length;
  let inRoot = true;
  let currentTable: TomlTable | null = null;
  let cursor = 0;

  while (cursor < text.length) {
    const lineStart = cursor;
    cursor = skipHorizontalWhitespace(text, cursor);
    if (cursor >= text.length) break;
    if (isNewline(text[cursor])) {
      cursor = skipNewline(text, cursor);
      continue;
    }
    if (text[cursor] === "#") {
      cursor = skipLine(text, cursor);
      continue;
    }
    if (text[cursor] === "[") {
      if (currentTable) currentTable.end = lineStart;
      if (inRoot) {
        inRoot = false;
        rootEnd = lineStart;
      }
      const parsedTable = parseTomlTable(text, cursor);
      currentTable = {
        key: parsedTable.key,
        array: parsedTable.array,
        end: text.length,
        assignments: [],
      };
      tables.push(currentTable);
      cursor = parsedTable.next;
      continue;
    }

    const assignment = parseTomlAssignment(text, cursor);
    if (inRoot) rootAssignments.push(assignment.assignment);
    else currentTable?.assignments.push(assignment.assignment);
    cursor = assignment.next;
  }

  return { rootAssignments, rootEnd, tables };
}

function updateTopLevelToml(
  text: string,
  document: TomlDocument,
  updates: Array<readonly [string, string]>,
): string {
  const ownedKeys = new Set(updates.map(([key]) => key));
  const conflictingTable = document.tables.find((table) => ownedKeys.has(table.key[0] ?? ""));
  if (conflictingTable) {
    throw new Error(
      `Cannot update Isolated config: TOML table namespace begins with owned scalar key ${JSON.stringify(conflictingTable.key[0])}`,
    );
  }
  return updateTomlAssignments(
    text,
    document.rootAssignments,
    document.rootEnd,
    updates,
    "top-level",
  );
}

function replaceTomlValue(text: string, assignment: TomlAssignment, value: string): string {
  return text.slice(0, assignment.valueStart) + value + text.slice(assignment.valueEnd);
}

function updateTomlAssignments(
  text: string,
  assignments: TomlAssignment[],
  insertionOffset: number,
  updates: Array<readonly [string, string]>,
  scope: string,
): string {
  const edits: Array<{ start: number; end: number; replacement: string }> = [];
  const missing: Array<readonly [string, string]> = [];
  for (const [key, value] of updates) {
    const conflictingDottedKey = assignments.some(
      (assignment) => assignment.key.length > 1 && assignment.key[0] === key,
    );
    if (conflictingDottedKey) {
      throw new Error(
        `Cannot update Isolated config: ${scope} TOML key ${JSON.stringify(key)} has an incompatible dotted shape`,
      );
    }
    const matches = assignments.filter(
      (assignment) => assignment.key.length === 1 && assignment.key[0] === key,
    );
    if (matches.length > 1) {
      throw new Error(`Cannot update Isolated config: duplicate ${scope} TOML key ${JSON.stringify(key)}`);
    }
    const match = matches[0];
    if (match) edits.push({ start: match.valueStart, end: match.valueEnd, replacement: value });
    else missing.push([key, value]);
  }

  if (missing.length > 0) {
    const newline = text.includes("\r\n") ? "\r\n" : "\n";
    const prefix = text.slice(0, insertionOffset);
    const leadingNewline = prefix.length > 0 && !prefix.endsWith("\n") && !prefix.endsWith("\r") ? newline : "";
    const insertion = `${leadingNewline}${missing.map(([key, value]) => `${key} = ${value}${newline}`).join("")}`;
    edits.push({ start: insertionOffset, end: insertionOffset, replacement: insertion });
  }

  edits.sort((left, right) => right.start - left.start);
  let updated = text;
  for (const edit of edits) {
    updated = updated.slice(0, edit.start) + edit.replacement + updated.slice(edit.end);
  }
  return updated;
}

function parseTomlAssignment(
  text: string,
  start: number,
): { assignment: TomlAssignment; next: number } {
  const parsedKey = parseTomlDottedKey(text, start, "=");
  let valueStart = skipHorizontalWhitespace(text, parsedKey.next + 1);
  if (valueStart >= text.length || isNewline(text[valueStart]) || text[valueStart] === "#") {
    throw new Error("Cannot update Isolated config: TOML assignment has no value");
  }
  const value = scanTomlValue(text, valueStart);
  return {
    assignment: { key: parsedKey.key, valueStart, valueEnd: value.valueEnd },
    next: value.next,
  };
}

function parseTomlTable(text: string, start: number): { key: string[]; array: boolean; next: number } {
  const arrayTable = text.startsWith("[[", start);
  const openLength = arrayTable ? 2 : 1;
  const close = arrayTable ? "]]" : "]";
  const parsedKey = parseTomlDottedKey(text, start + openLength, close);
  let cursor = skipHorizontalWhitespace(text, parsedKey.next + close.length);
  if (cursor < text.length && text[cursor] !== "#" && !isNewline(text[cursor])) {
    throw new Error("Cannot update Isolated config: invalid TOML table header");
  }
  cursor = skipLine(text, cursor);
  return { key: parsedKey.key, array: arrayTable, next: cursor };
}

function parseTomlDottedKey(
  text: string,
  start: number,
  terminator: "=" | "]" | "]]",
): { key: string[]; next: number } {
  const key: string[] = [];
  let cursor = skipHorizontalWhitespace(text, start);
  while (cursor < text.length) {
    const segment = parseTomlKeySegment(text, cursor);
    key.push(segment.value);
    cursor = skipHorizontalWhitespace(text, segment.next);
    if (text.startsWith(terminator, cursor)) return { key, next: cursor };
    if (text[cursor] !== ".") {
      throw new Error("Cannot update Isolated config: invalid TOML key");
    }
    cursor = skipHorizontalWhitespace(text, cursor + 1);
  }
  throw new Error("Cannot update Isolated config: unterminated TOML key");
}

function parseTomlKeySegment(text: string, start: number): { value: string; next: number } {
  const quote = text[start];
  if (quote === '"' || quote === "'") {
    let cursor = start + 1;
    let escaped = false;
    while (cursor < text.length) {
      const char = text[cursor];
      if (quote === '"' && escaped) {
        escaped = false;
        cursor += 1;
        continue;
      }
      if (quote === '"' && char === "\\") {
        escaped = true;
        cursor += 1;
        continue;
      }
      if (char === quote) {
        const raw = text.slice(start + 1, cursor);
        return {
          value: quote === '"' ? decodeTomlBasicString(raw) : raw,
          next: cursor + 1,
        };
      }
      if (isNewline(char)) throw new Error("Cannot update Isolated config: newline in TOML key");
      cursor += 1;
    }
    throw new Error("Cannot update Isolated config: unterminated quoted TOML key");
  }

  let cursor = start;
  while (cursor < text.length && /[A-Za-z0-9_-]/.test(text[cursor])) cursor += 1;
  if (cursor === start) throw new Error("Cannot update Isolated config: invalid TOML bare key");
  return { value: text.slice(start, cursor), next: cursor };
}

function decodeTomlBasicString(raw: string): string {
  let decoded = "";
  let cursor = 0;
  while (cursor < raw.length) {
    if (raw[cursor] !== "\\") {
      decoded += raw[cursor];
      cursor += 1;
      continue;
    }
    const escape = readTomlEscape(raw, cursor);
    decoded += escape.value;
    cursor = escape.next;
  }
  return decoded;
}

function scanTomlValue(text: string, start: number): { valueEnd: number; next: number } {
  let cursor = start;
  let quote: "basic" | "literal" | "multi-basic" | "multi-literal" | null = null;
  let squareDepth = 0;
  let curlyDepth = 0;

  while (cursor < text.length) {
    const char = text[cursor];
    if (quote === "basic") {
      if (char === "\\") {
        cursor = skipTomlEscape(text, cursor, false);
        continue;
      }
      if (char === '"') quote = null;
      else if (isNewline(char)) throw new Error("Cannot update Isolated config: newline in TOML string");
      cursor += 1;
      continue;
    }
    if (quote === "literal") {
      if (char === "'") quote = null;
      else if (isNewline(char)) throw new Error("Cannot update Isolated config: newline in TOML literal string");
      cursor += 1;
      continue;
    }
    if (quote === "multi-basic") {
      if (char === "\\") {
        cursor = skipTomlEscape(text, cursor, true);
        continue;
      }
      if (char === '"') {
        const quoteCount = countRun(text, cursor, '"');
        if (quoteCount >= 3) {
          if (quoteCount > 5) {
            throw new Error("Cannot update Isolated config: invalid quote run in TOML multiline string");
          }
          quote = null;
        }
        cursor += quoteCount;
        continue;
      }
      cursor += 1;
      continue;
    }
    if (quote === "multi-literal") {
      if (char === "'") {
        const quoteCount = countRun(text, cursor, "'");
        if (quoteCount >= 3) {
          if (quoteCount > 5) {
            throw new Error("Cannot update Isolated config: invalid quote run in TOML multiline string");
          }
          quote = null;
        }
        cursor += quoteCount;
        continue;
      }
      cursor += 1;
      continue;
    }

    if (text.startsWith('"""', cursor)) {
      quote = "multi-basic";
      cursor += 3;
      continue;
    }
    if (text.startsWith("'''", cursor)) {
      quote = "multi-literal";
      cursor += 3;
      continue;
    }
    if (char === '"') {
      quote = "basic";
      cursor += 1;
      continue;
    }
    if (char === "'") {
      quote = "literal";
      cursor += 1;
      continue;
    }
    if (char === "[") squareDepth += 1;
    else if (char === "]") squareDepth -= 1;
    else if (char === "{") curlyDepth += 1;
    else if (char === "}") curlyDepth -= 1;
    else if (char === "#") {
      if (squareDepth === 0 && curlyDepth === 0) {
        return { valueEnd: trimHorizontalEnd(text, start, cursor), next: skipLine(text, cursor) };
      }
      cursor = skipLine(text, cursor);
      continue;
    } else if (isNewline(char) && squareDepth === 0 && curlyDepth === 0) {
      return { valueEnd: trimHorizontalEnd(text, start, cursor), next: skipNewline(text, cursor) };
    }
    if (squareDepth < 0 || curlyDepth < 0) {
      throw new Error("Cannot update Isolated config: unbalanced TOML value");
    }
    cursor += 1;
  }

  if (quote || squareDepth !== 0 || curlyDepth !== 0) {
    throw new Error("Cannot update Isolated config: unterminated TOML value");
  }
  return { valueEnd: trimHorizontalEnd(text, start, cursor), next: cursor };
}

function skipHorizontalWhitespace(text: string, start: number): number {
  let cursor = start;
  while (text[cursor] === " " || text[cursor] === "\t") cursor += 1;
  return cursor;
}

function countRun(text: string, start: number, value: string): number {
  let cursor = start;
  while (text[cursor] === value) cursor += 1;
  return cursor - start;
}

function skipTomlEscape(text: string, start: number, allowLineContinuation: boolean): number {
  const marker = text[start + 1];
  if (allowLineContinuation && isNewline(marker)) {
    let cursor = skipNewline(text, start + 1);
    while (cursor < text.length) {
      if (text[cursor] === " " || text[cursor] === "\t") cursor += 1;
      else if (isNewline(text[cursor])) cursor = skipNewline(text, cursor);
      else break;
    }
    return cursor;
  }
  return readTomlEscape(text, start).next;
}

function readTomlEscape(text: string, start: number): { value: string; next: number } {
  const marker = text[start + 1];
  const simple: Record<string, string> = {
    b: "\b",
    t: "\t",
    n: "\n",
    f: "\f",
    r: "\r",
    '"': '"',
    "\\": "\\",
  };
  if (marker !== undefined && Object.hasOwn(simple, marker)) {
    return { value: simple[marker], next: start + 2 };
  }
  if (marker === "u" || marker === "U") {
    const length = marker === "u" ? 4 : 8;
    const digits = text.slice(start + 2, start + 2 + length);
    if (digits.length !== length || !/^[0-9A-Fa-f]+$/.test(digits)) {
      throw new Error("Cannot update Isolated config: invalid TOML Unicode escape");
    }
    const point = Number.parseInt(digits, 16);
    if (point > 0x10ffff || (point >= 0xd800 && point <= 0xdfff)) {
      throw new Error("Cannot update Isolated config: invalid TOML Unicode escape");
    }
    return { value: String.fromCodePoint(point), next: start + 2 + length };
  }
  throw new Error("Cannot update Isolated config: invalid TOML escape");
}

function trimHorizontalEnd(text: string, start: number, end: number): number {
  let cursor = end;
  while (cursor > start && (text[cursor - 1] === " " || text[cursor - 1] === "\t")) cursor -= 1;
  return cursor;
}

function skipLine(text: string, start: number): number {
  let cursor = start;
  while (cursor < text.length && !isNewline(text[cursor])) cursor += 1;
  return skipNewline(text, cursor);
}

function skipNewline(text: string, start: number): number {
  if (text[start] === "\r" && text[start + 1] === "\n") return start + 2;
  if (isNewline(text[start])) return start + 1;
  return start;
}

function isNewline(value: string | undefined): boolean {
  return value === "\n" || value === "\r";
}

function replaceFileAtomic(filePath: string, body: string, mode: number): void {
  const parent = path.dirname(filePath);
  fs.mkdirSync(parent, { recursive: true });
  const tempPath = path.join(
    parent,
    `.${path.basename(filePath)}.${process.pid}.${crypto.randomUUID()}.tmp`,
  );
  let fileDescriptor: number | null = null;
  try {
    fileDescriptor = fs.openSync(tempPath, "wx", mode);
    fs.fchmodSync(fileDescriptor, mode);
    fs.writeFileSync(fileDescriptor, body, "utf8");
    fs.fsyncSync(fileDescriptor);
    fs.closeSync(fileDescriptor);
    fileDescriptor = null;
    fs.renameSync(tempPath, filePath);
    const directoryDescriptor = fs.openSync(parent, "r");
    try {
      fs.fsyncSync(directoryDescriptor);
    } finally {
      fs.closeSync(directoryDescriptor);
    }
  } catch (error) {
    if (fileDescriptor !== null) {
      try {
        fs.closeSync(fileDescriptor);
      } catch {
        // Preserve the original failure.
      }
    }
    try {
      fs.unlinkSync(tempPath);
    } catch {
      // The temporary file may not have been created or may already have been renamed.
    }
    throw error;
  }
}

function writeIfMissing(filePath: string, body: string): void {
  if (fs.existsSync(filePath)) return;
  writeProductFile(filePath, body);
}

function writeProductFile(filePath: string, body: string): void {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, body, { encoding: "utf8", mode: 0o644 });
}

function ensureGitRoot(workspaceDir: string): void {
  if (!fs.existsSync(path.join(workspaceDir, ".git"))) {
    const result = spawnSync("git", ["init"], { cwd: workspaceDir, encoding: "utf8" });
    if (result.error) {
      throw new Error(`Git initialization failed for Workspace: ${result.error.message}`);
    }
    if (result.status !== 0) {
      const detail = result.stderr.trim() || `git exited with status ${result.status ?? "unknown"}`;
      throw new Error(`Git initialization failed for Workspace: ${detail}`);
    }
  }
  const result = spawnSync("git", ["rev-parse", "--show-toplevel"], {
    cwd: workspaceDir,
    encoding: "utf8",
  });
  if (result.error) {
    throw new Error(`Git repository validation failed for Workspace: ${result.error.message}`);
  }
  if (result.status !== 0) {
    const detail = result.stderr.trim() || `git exited with status ${result.status ?? "unknown"}`;
    throw new Error(`Git repository validation failed for Workspace: ${detail}`);
  }
  const expectedRoot = fs.realpathSync(workspaceDir);
  if (!result.stdout.endsWith("\n")) {
    throw new Error("Git repository validation failed for Workspace: git returned an unterminated root record");
  }
  const reportedRoot = result.stdout.slice(0, -1);
  let resolvedRoot: string;
  try {
    resolvedRoot = fs.realpathSync(reportedRoot);
  } catch {
    throw new Error(
      `Git repository validation failed for Workspace: git reported an unusable root ${JSON.stringify(reportedRoot)}`,
    );
  }
  if (resolvedRoot !== expectedRoot) {
    throw new Error(
      `Git repository validation failed for Workspace: repository root ${JSON.stringify(resolvedRoot)} does not match ${JSON.stringify(expectedRoot)}`,
    );
  }
}

function ensureFileSymlink(linkPath: string, target: string): void {
  try {
    const stat = fs.lstatSync(linkPath);
    if (stat.isSymbolicLink()) {
      if (fs.readlinkSync(linkPath) === target) return;
      fs.unlinkSync(linkPath);
    } else {
      return;
    }
  } catch {
    // missing
  }
  fs.symlinkSync(target, linkPath);
}

