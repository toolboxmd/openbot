export type PreparedBotWorkspace = {
  dir: string;
  created: boolean;
};

export type BotWorkspaceRollback = {
  removed: boolean;
  preservedPath?: string;
  reason?: string;
};

export class BotWorkspacePreparationError extends Error {
  constructor(
    readonly preparedWorkspace: PreparedBotWorkspace,
    cause: unknown,
  ) {
    super(errorMessage(cause), { cause });
    this.name = "BotWorkspacePreparationError";
  }
}

export function prepareBotWorkspace(workspaceDir: string, botId: string): PreparedBotWorkspace {
  const dir = botWorkspaceDir(workspaceDir, botId);
  fs.mkdirSync(path.dirname(dir), { recursive: true });
  let created = false;
  try {
    fs.mkdirSync(dir);
    created = true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EEXIST" || !fs.lstatSync(dir).isDirectory()) throw error;
  }
  const preparedWorkspace = { dir, created };
  try {
    writeIfMissing(thisBotAgentsPath(workspaceDir, botId), THIS_BOT_AGENTS_MD);
    ensureFileSymlink(path.join(dir, "CLAUDE.md"), "AGENTS.md");
    return preparedWorkspace;
  } catch (error) {
    throw new BotWorkspacePreparationError(preparedWorkspace, error);
  }
}

export function ensureBotWorkspace(workspaceDir: string, botId: string): string {
  return prepareBotWorkspace(workspaceDir, botId).dir;
}

export function rollbackPreparedBotWorkspace(prepared: PreparedBotWorkspace): BotWorkspaceRollback {
  if (!prepared.created) {
    return {
      removed: false,
      preservedPath: prepared.dir,
      reason: "the Bot workspace existed before this creation attempt",
    };
  }
  try {
    fs.rmdirSync(prepared.dir);
    return { removed: true };
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code === "ENOENT") return { removed: true };
    if (code !== "ENOTEMPTY" && code !== "EEXIST") {
      return {
        removed: false,
        preservedPath: prepared.dir,
        reason: `the new Bot workspace could not be confirmed empty: ${errorMessage(error)}`,
      };
    }
  }
  const quarantinePath = path.join(
    path.dirname(prepared.dir),
    `.${path.basename(prepared.dir)}.${crypto.randomUUID()}.rollback`,
  );
  try {
    fs.renameSync(prepared.dir, quarantinePath);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { removed: true };
    return {
      removed: false,
      preservedPath: prepared.dir,
      reason: `the new Bot workspace could not be isolated for cleanup: ${errorMessage(error)}`,
    };
  }

  const restore = (reason: string): BotWorkspaceRollback => {
    try {
      fs.renameSync(quarantinePath, prepared.dir);
      return { removed: false, preservedPath: prepared.dir, reason };
    } catch (error) {
      return {
        removed: false,
        preservedPath: quarantinePath,
        reason: `${reason}; it could not be restored to its original path: ${errorMessage(error)}`,
      };
    }
  };

  try {
    fs.rmdirSync(quarantinePath);
    return { removed: true };
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code !== "ENOTEMPTY" && code !== "EEXIST") {
      return restore(`the new Bot workspace could not be removed safely: ${errorMessage(error)}`);
    }
  }

  try {
    const artifacts = removableBotWorkspaceArtifacts(quarantinePath);
    if (!artifacts) {
      return restore("the new Bot workspace changed after OpenBot prepared it");
    }
    for (const artifact of artifacts) fs.unlinkSync(path.join(quarantinePath, artifact));
    fs.rmdirSync(quarantinePath);
    return { removed: true };
  } catch (error) {
    return restore(`the new Bot workspace could not be removed safely: ${errorMessage(error)}`);
  }
}

function removableBotWorkspaceArtifacts(dir: string): string[] | null {
  const workspaceStat = fs.lstatSync(dir);
  if (!workspaceStat.isDirectory() || workspaceStat.isSymbolicLink()) return null;
  const entries = fs.readdirSync(dir).sort();
  if (entries.length < 1 || entries.length > 2 || entries[0] !== "AGENTS.md") return null;
  if (entries.length === 2 && entries[1] !== "CLAUDE.md") return null;
  const agentsPath = path.join(dir, "AGENTS.md");
  const claudePath = path.join(dir, "CLAUDE.md");
  if (!fs.lstatSync(agentsPath).isFile()) return null;
  if (fs.readFileSync(agentsPath, "utf8") !== THIS_BOT_AGENTS_MD) return null;
  if (entries.includes("CLAUDE.md")) {
    if (!fs.lstatSync(claudePath).isSymbolicLink()) return null;
    if (fs.readlinkSync(claudePath) !== "AGENTS.md") return null;
  }
  return entries.includes("CLAUDE.md") ? ["CLAUDE.md", "AGENTS.md"] : ["AGENTS.md"];
}

