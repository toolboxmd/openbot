export type SessionEnvOpts = {
  botId?: string;
  screenContainer?: string;
};

export function applyVendorHomeEnv(
  env: NodeJS.ProcessEnv,
  mode: ConfigMode,
  homeDir: string,
  botHome?: string,
  session?: SessionEnvOpts,
): NodeJS.ProcessEnv {
  const next = { ...env };
  for (const id of HARNESS_IDS) {
    const key = VENDOR_HOME_ENV[id];
    if (mode === "isolated") next[key] = vendorDir(homeDir, id);
    else delete next[key];
  }
  next.OPENBOT_CONFIG_MODE = mode;
  if (mode === "isolated") {
    const workspaceBotId = botIdFromBotHome(botHome);
    if (session?.botId !== undefined) assertGeneratedBotId(session.botId);
    if (workspaceBotId && session?.botId && workspaceBotId !== session.botId) {
      throw Object.assign(new Error("Bot ID does not match Bot workspace"), {
        status: 400,
        code: "BOT_WORKSPACE_MISMATCH",
      });
    }
    if (botHome) next.HOME = path.resolve(botHome);
    const botId = session?.botId ?? workspaceBotId;
    if (botId) next.OPENBOT_BOT_ID = botId;
    next.OPENBOT_SCREEN_CONTAINER =
      session?.screenContainer ?? env.OPENBOT_SCREEN_CONTAINER ?? COMPUTER_CONTAINER;
    next.OPENBOT_SCREEN_WORKSPACE = WORKSPACE_MOUNT;
  } else {
    delete next.OPENBOT_BOT_ID;
    delete next.OPENBOT_SCREEN_CONTAINER;
    delete next.OPENBOT_SCREEN_WORKSPACE;
  }
  return next;
}

function botIdFromBotHome(botHome: string | undefined): string | undefined {
  if (!botHome) return undefined;
  const resolved = path.resolve(botHome);
  if (resolved !== botHome) {
    throw Object.assign(new Error("Invalid Bot workspace path: expected an absolute canonical path"), {
      status: 400,
      code: "INVALID_BOT_WORKSPACE",
    });
  }
  const parts = resolved.split(path.sep);
  const idx = parts.lastIndexOf("bots");
  const id = idx >= 0 ? parts[idx + 1] : undefined;
  if (!id || idx !== parts.length - 2) {
    throw Object.assign(new Error("Invalid Bot workspace path: expected Workspace/bots/<Bot ID>"), {
      status: 400,
      code: "INVALID_BOT_WORKSPACE",
    });
  }
  assertGeneratedBotId(id);
  return id;
}

